/* ---------- واجهة الموسوعة ---------- */
const grid = () => document.getElementById('ency-grid');
const emptyMsg = () => document.getElementById('ency-empty');

let activeFilter = 'all';
let searchTerm = '';

/** عرض شرائح التصفية */
export function renderEncyFilters() {
  const wrap = document.getElementById('ency-filters');
  if (!wrap) return;
  const chips = [['all', 'الكل'], ...Object.entries(ENCY_CATEGORIES)];
  wrap.innerHTML = chips.map(([key, label]) =>
    `<button class="badge ${activeFilter === key ? 'red' : ''}" data-cat="${key}" role="tab"
      aria-selected="${activeFilter === key}" style="cursor:pointer;font-size:.8rem;padding:7px 14px">${label}</button>`
  ).join('');
  wrap.querySelectorAll('button[data-cat]').forEach(btn => {
    btn.addEventListener('click', () => {
      activeFilter = btn.dataset.cat;
      renderEncyFilters();
      renderEncyGrid();
    });
  });
}

/** عرض بطاقات الموسوعة بحسب البحث والتصفية */
export function renderEncyGrid() {
  const g = grid();
  if (!g) return;
  const term = searchTerm.trim();
  const items = ENCYCLOPEDIA.filter(card => {
    const byCat = activeFilter === 'all' || card.cat === activeFilter;
    const bySearch = term === '' ||
      card.title.includes(term) || card.text.includes(term) ||
      (ENCY_CATEGORIES[card.cat] || '').includes(term);
    return byCat && bySearch;
  });
  emptyMsg().classList.toggle('hidden', items.length > 0);
  g.innerHTML = items.map(card => {
    const read = player.data.encyReads.includes(card.id);
    return `
      <button class="card ency-card" data-ency="${card.id}" style="text-align:right;cursor:pointer;transition:transform .18s ease"
              aria-label="اقرأ عن ${card.title}">
        <div class="row">
          <span style="font-size:1.6rem">${card.icon}</span>
          <div class="grow">
            <b style="display:block;font-size:.98rem">${card.title}</b>
            <span class="badge" style="margin-top:4px">${ENCY_CATEGORIES[card.cat]}</span>
          </div>
          ${read ? '<span class="badge green">✓ مقروءة</span>' : ''}
        </div>
      </button>`;
  }).join('');
  g.querySelectorAll('[data-ency]').forEach(el => {
    el.addEventListener('click', () => openEncyCard(el.dataset.ency));
  });
}

/** فتح بطاقة موسوعة في نافذة */
export function openEncyCard(id) {
  const card = ENCYCLOPEDIA.find(c => c.id === id);
  if (!card) return;
  const body = document.getElementById('ency-modal-body');
  body.innerHTML = `
    <div class="row mb-2">
      <span style="font-size:2rem">${card.icon}</span>
      <div class="grow">
        <h3>${card.title}</h3>
        <span class="badge red">${ENCY_CATEGORIES[card.cat]}</span>
      </div>
    </div>
    <p style="line-height:2.1;font-weight:600">${card.text}</p>
    <div class="modal-actions">
      <button class="btn btn-primary" id="ency-close-btn">حسنًا</button>
    </div>`;
  document.getElementById('modal-ency').classList.add('open');
  document.getElementById('ency-close-btn').addEventListener('click', closeEncyCard);
  player.markEncyRead(card.id);
}

export function closeEncyCard() {
  document.getElementById('modal-ency').classList.remove('open');
  renderEncyGrid(); // لتحديث شارة "مقروءة"
}

/** تهيئة أحداث البحث */
export function initEncyclopedia() {
  const search = document.getElementById('ency-search');
  search.addEventListener('input', () => {
    searchTerm = search.value;
    renderEncyGrid();
  });
  renderEncyFilters();
  renderEncyGrid();
}
